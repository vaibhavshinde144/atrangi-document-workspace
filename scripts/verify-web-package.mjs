import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { gunzipSync } from 'node:zlib';

const root=path.resolve(import.meta.dirname,'..');
const docs=path.join(root,'docs');
const loader=fs.readFileSync(path.join(docs,'index.html'),'utf8');
const list=loader.match(/const names=\[([^\]]+)\]/);
assert.ok(list,'index must declare app chunks');
const chunks=[...list[1].matchAll(/'([^']+)'/g)].map(m=>m[1]);
assert.equal(chunks.length,7,'expected seven application chunks');
const encoded=chunks.map(name=>{const f=path.join(docs,name);assert.ok(fs.existsSync(f),`missing chunk ${name}`);return fs.readFileSync(f,'utf8').trim()}).join('');
const app=gunzipSync(Buffer.from(encoded,'base64')).toString('utf8');
assert.match(app,/<!doctype html>/i,'decoded bundle must be HTML');
for(const token of ['class="topbar"','class="brand-block"','class="brand-logo"','class="top-actions"','id="homePanel"','id="desktopNav"','id="mobileNav"'])assert.ok(app.includes(token),`missing base UI contract ${token}`);
const refs=[...app.matchAll(/<(?:link|script)[^>]+(?:href|src)="([^"]+)"[^>]*>/gi)].map(m=>m[1]);
const local=refs.filter(u=>!/^(?:[a-z]+:|\/\/|#|data:)/i.test(u)).map(u=>u.split(/[?#]/,1)[0]);
for(const asset of new Set(local))assert.ok(fs.existsSync(path.join(docs,asset)),`missing base asset ${asset}`);
for(const asset of ['branding-v718.css','branding-v718.js','atrangi-brand-logo.svg','hardening-v715.css','hardening-v715.js'])assert.ok(fs.existsSync(path.join(docs,asset)),`missing release asset ${asset}`);
assert.match(fs.readFileSync(path.join(docs,'atrangi-brand-logo.svg'),'utf8'),/<svg\b/i,'logo asset must be SVG');
const version=JSON.parse(fs.readFileSync(path.join(docs,'version.json'),'utf8'));
assert.equal(version.webVersion,'7.1.8','version.json must be v7.1.8');
assert.match(loader,/release='718'/,'loader must use release 718');
for(const token of ['brandHomeBtn','themeToggleBtn','atrangi-brand-logo.svg','branding-v718.css','branding-v718.js'])assert.ok(loader.includes(token),`bootstrap missing ${token}`);
const writeAt=loader.indexOf('document.write(text)');
assert.ok(loader.indexOf('branding-v718.js')<writeAt,'branding script must be embedded in decoded document before document.write');
assert.ok(loader.indexOf('branding-v718.css')<writeAt,'branding stylesheet must be embedded in decoded document before document.write');
const inline=loader.match(/<script>([\s\S]*?)<\/script>/i)?.[1];
assert.ok(inline,'bootstrap inline JS missing');
assert.doesNotThrow(()=>new Function(inline),'bootstrap JS must parse');
const branding=fs.readFileSync(path.join(docs,'branding-v718.js'),'utf8');
assert.doesNotThrow(()=>new Function(branding),'branding JS must parse');
for(const token of ["VERSION='7.1.8'",'themeToggleBtn','brandingTest','brandHomeBtn'])assert.ok(branding.includes(token),`branding runtime missing ${token}`);
const sw=fs.readFileSync(path.join(docs,'sw.js'),'utf8');
assert.doesNotThrow(()=>new Function(sw),'service worker JS must parse');
console.log(`Verified v7.1.8 package: ${chunks.length} chunks, ${new Set(local).size} bundled assets.`);
